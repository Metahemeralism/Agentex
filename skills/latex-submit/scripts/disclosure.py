#!/usr/bin/env python3
"""Draft an LLM-use disclosure paragraph from what the agent actually did.

Usage: disclosure.py [project]          (default: current folder)
Reads .agentex/activity.jsonl (written by hooks/activity_log.py on every agent edit to .tex/.bib),
`git log` (commits with a Co-Authored-By: Claude trailer), and AgenTeX state (citation cache, results
registry, compile loop). Prints a LaTeX paragraph marked as a DRAFT with [AUTHORS: ...] gaps that
preflight.py reports as placeholders until the authors edit them. Nothing is written to the paper.
Stdlib only.
"""
import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

SKIP = {'.git', '.agentex', 'arxiv_submission', 'build', 'out', 'node_modules'}
CLAUDE_TRAILER = re.compile(r'^co-authored-by:.*\bclaude\b', re.I | re.M)


def find_up(start, rel):
    """First <dir>/<rel> that exists at or above `start`, stopping at the git root."""
    start = Path(start).resolve()
    for d in [start, *start.parents]:
        if (d / rel).exists():
            return d / rel
        if (d / '.git').exists():
            return None
    return None


def agentex_root(start):
    """Folder whose .agentex/ holds AgenTeX state for `start`: the nearest one above it, else `start`."""
    found = find_up(start, '.agentex')
    return found.parent if found else Path(start).resolve()


def read_activity(start):
    """Agent edits logged by hooks/activity_log.py (in the session folder, at or above `start`)."""
    log, out = find_up(start, '.agentex/activity.jsonl'), []
    try:
        for line in log.read_text(encoding='utf-8').splitlines() if log else []:
            try:
                out.append(json.loads(line))
            except ValueError:
                pass  # a half-written line from an interrupted hook
    except OSError:
        pass
    return out


def git_counts(root):
    """-> (commits touching .tex/.bib, of which co-authored by Claude), or None outside git."""
    try:
        r = subprocess.run(['git', 'log', '--format=%B%x1e', '--', '*.tex', '*.bib'], cwd=root,
                           capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    if r.returncode:
        return None
    msgs = [m for m in r.stdout.split('\x1e') if m.strip()]
    return len(msgs), sum(bool(CLAUDE_TRAILER.search(m)) for m in msgs)


def tex_lines(root):
    return sum(len(p.read_text(encoding='utf-8', errors='replace').splitlines())
               for p in root.rglob('*.tex') if not SKIP & set(p.relative_to(root).parts))


def state(root):
    """What AgenTeX verified: {'citations': {status: n}, 'res_uses': n, 'compile_loop': bool}."""
    out = {}
    try:
        keys = json.loads(find_up(root, '.agentex/cite-cache.json').read_text()).get('keys', {})
        counts = defaultdict(int)
        for k in keys.values():
            counts[k.get('status', '?')] += 1
        out['citations'] = dict(counts)
    except (AttributeError, OSError, ValueError):
        pass  # never verified
    out['res_uses'] = sum(len(re.findall(r'\\res(?:pct)?\{', p.read_text(encoding='utf-8', errors='replace')))
                          for p in root.rglob('*.tex') if not SKIP & set(p.relative_to(root).parts))
    out['compile_loop'] = find_up(root, '.agentex/build-state.json') is not None
    return out


def plural(n, word):
    return f'{n} {word}' + ('' if n == 1 else 's')


def summarize(entries):
    files, sections = defaultdict(lambda: [0, 0]), []
    for e in entries:
        files[e.get('file', '?')][0] += int(e.get('added_lines', 0))
        files[e.get('file', '?')][1] += int(e.get('removed_lines', 0))
        if e.get('section') and e['section'] not in sections:
            sections.append(e['section'])
    times = sorted(e.get('time', '') for e in entries if e.get('time'))
    return files, sections, (times[0][:10], times[-1][:10]) if times else None


def draft(project):
    root = Path(project).resolve()
    entries = read_activity(root)
    files, sections, span = summarize(entries)
    added = sum(a for a, _ in files.values())
    total = tex_lines(root)
    git = git_counts(root)
    st = state(root)
    s = ['% DRAFT LLM-use disclosure generated by AgenTeX (latex-submit/scripts/disclosure.py).',
         '% The authors must check, edit and own every sentence; preflight.py fails while [AUTHORS: ...] gaps remain.',
         '% Put it where your venue asks (e.g. ICLR: a section on LLM usage; IEEE/ACM: the acknowledgements).']
    body = ['We used an LLM-based coding agent ([AUTHORS: model name and version], run in Claude Code with the '
            'AgenTeX plugin) while preparing this paper.']
    if entries:
        where = ', '.join(sections[:8]) if sections else ', '.join(sorted(files)[:8])
        share = f' (at most about {min(100, round(100 * added / total))}\\% of the current {total} lines of LaTeX source)' if total else ''
        when = f'On {span[0]}' if span[0] == span[1] else f'Between {span[0]} and {span[1]}'
        body.append(f'{when} it made {plural(len(entries), "edit")} to {plural(len(files), "source file")} '
                    f'({where}), adding {added} and removing {sum(r for _, r in files.values())} lines{share}.')
    else:
        body.append('[AUTHORS: no agent edits were logged (.agentex/activity.jsonl is missing); describe which parts it drafted or edited.]')
    if git and git[1]:
        body.append(f'{git[1]} of the {git[0]} commits that changed the paper sources were co-authored by the agent.')
    cites = st.get('citations')
    if cites:
        ok = cites.get('verified', 0) + cites.get('published', 0)
        body.append(f'{sum(cites.values())} references were checked by a deterministic script against bibliographic '
                    f'databases (Crossref, arXiv, DBLP, OpenAlex); {ok} matched automatically'
                    + ('; [AUTHORS: say how the others were checked].' if ok < sum(cites.values()) else '.'))
    if st['res_uses']:
        body.append(f'Reported numbers ({st["res_uses"]} uses) are inserted from the experiment result files by script '
                    'rather than typed by hand.')
    if st['compile_loop']:
        body.append('The document was recompiled and checked automatically after each editing session.')
    body.append('[AUTHORS: state whether the agent contributed to research ideas, experiments, code or analysis, or only '
                'to writing and formatting.] The authors reviewed all content and take full responsibility for it.')
    return '\n'.join(s) + '\n' + ' '.join(body) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('project', nargs='?', default='.', type=Path)
    args = ap.parse_args(argv)
    if not args.project.is_dir():
        print(f'not a folder: {args.project}')
        return 2
    print(draft(args.project))
    return 0


if __name__ == '__main__':
    sys.exit(main())

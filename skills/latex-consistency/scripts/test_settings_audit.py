def make_project(root):
    """A code repo with configs in four formats plus a paper that discloses some settings,
    gets one wrong (layers) and omits others (seed, label smoothing, betas, ...)."""
    files = {
        'code/configs/train.yaml': YAML,
        'code/config.json': json.dumps({'model': {'hidden_size': 256, 'dropout': 0.1, 'num_layers': 4}, 'seed': 42}, indent=1),
        'code/setup.ini': '[train]\nlabel_smoothing = 0.1\nnum_workers = 8\n',
        'code/params.toml': '[schedule]\nwarmup_ratio = 0.06\n',
        'code/train.py': TRAIN_PY,
        'code/tests/test_x.py': 'f(lr=0.5)\n',  # tests are not the experiment
        'paper/main.tex': '\\documentclass{article}\n\\input{results}\n\\begin{document}\n\\input{sections/setup}\n\\end{document}\n',
        'paper/results.tex': '% Generated by AgenTeX results.py\n\\makeatletter\n\\@namedef{agx@res@cfg.warmup}{500}\n\\makeatother\n',
        'paper/sections/setup.tex': SETUP_TEX,
    }
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text)


def run(argv):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        code = main(argv)
    return code, out.getvalue()


class NormaliseTest(unittest.TestCase):
    def test_number_forms(self):
        forms = ['1e-3', '0.001', '$10^{-3}$', '1\\times10^{-3}', '1 \\cdot 10^{-3}', '\\num{1e-3}', '\\num[round-mode=places]{0.001}']
        for f in forms:
            vals = [num_value(m) for m in NUM.finditer(plain(f'rate {f} here'))]
            self.assertEqual(len(vals), 1, f)
            self.assertAlmostEqual(vals[0][0], 0.001, msg=f)
        self.assertEqual(num_value(next(NUM.finditer(plain('10\\%')))), (10.0, True))
        self.assertEqual([num_value(m)[0] for m in NUM.finditer(plain('50k steps, 1{,}000 and 3\\times 10^{4}; 1.5M'))],
                         [50000, 1000, 30000, 1.5e6])
        self.assertEqual([m[0] for m in NUM.finditer(plain('128bit \\beta_1 l2 ResNet50 fp16'))], [])

    def test_greek_and_registry(self):
        self.assertIn('eta = 1e-3', plain('$\\eta = 10^{-3}$'))
        self.assertIn('500 warmup', plain('\\res{cfg.w} warmup', {'cfg.w': '500'}))
        self.assertIn('91.3', plain('\\respct{acc}', {'acc': '0.913'}))


class ParseTest(unittest.TestCase):
    def test_yaml_subset(self):
        got = {'.'.join(p): (v, n) for p, v, n in parse_yaml(YAML + 'layers:\n  - size: 64\n    act: relu\n  - size: 32\nflow: {a: 1, b: "x"}\n')}
        self.assertEqual(got['optimizer.lr'], (3e-4, 3))
        self.assertEqual(got['optimizer.name'], ('adamw', 2))
        self.assertEqual(got['optimizer.betas'], ([0.9, 0.999], 5))
        self.assertEqual(got['data.splits'], (['train', 'val'], 18))
        self.assertEqual(got['layers.0.size'][0], 64)
        self.assertEqual(got['layers.0.act'][0], 'relu')
        self.assertEqual(got['layers.1.size'][0], 32)
        self.assertEqual(got['flow.b'][0], 'x')
        self.assertNotIn('training.notes.lr', got)  # inside a block scalar

    def test_python_ast(self):
        got = {s['label']: (s['value'], s['line']) for s in py_settings(TRAIN_PY, Path('train.py'))}
        self.assertEqual(got['--lr'], (1e-3, 4))
        self.assertEqual(got['--ema-decay'], (0.999, 6))
        self.assertEqual(got['Cfg.temperature'], (0.07, 9))
        self.assertEqual(got['Cfg.patience'], (5, 10))
        self.assertEqual(got['AdamW(...)'], ('AdamW', 11))
        self.assertEqual(got['AdamW(lr=)'], (3e-4, 11))
        self.assertEqual(got['DataLoader(batch_size=)'], (64, 12))
        self.assertEqual(got['clip_grad_norm_(max_grad_norm)'], (1.0, 13))
        self.assertEqual(got['manual_seed(seed)'], (42, 14))
        self.assertFalse({'--device', 'DataLoader(num_workers=)', 'DataLoader(shuffle=)'} & set(got))  # noise


class AuditTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        make_project(self.root)

    def tearDown(self):
        self.tmp.cleanup()

    def test_classification(self):
        code, out = run([str(self.root / 'code'), str(self.root / 'paper'), '--root', str(self.root), '--limit', '0'])
        self.assertEqual(code, 1)
        rows = {m[2]: m[1] for m in re.finditer(r'^(\S+)\s+(\S+)=\S+', out, re.M)}
        self.assertEqual(rows['model.num_layers'], 'MISMATCH')
        self.assertIn('paper: 6 (paper/sections/setup.tex:3)', out)
        for label in ('seed', 'train.label_smoothing', 'optimizer.betas', 'Cfg.temperature', 'Cfg.patience', '--ema-decay',
                      'data.min_length'):
            self.assertEqual(rows.get(label), 'UNDISCLOSED', label)
        self.assertEqual(rows['clip_grad_norm_(max_grad_norm)'], 'NO-VALUE')
        # disclosed via 3\times10^{-4}, 10\%, \res{} and the optimizer name; a 2nd lr in the code is still pointed out
        self.assertEqual(rows['AdamW(lr=)'], 'DISCLOSED')
        self.assertIn('also 0.001 at code/train.py:4', out)
        self.assertEqual(rows['training.warmup_steps'], 'DISCLOSED')  # via \res{cfg.warmup}
        for label in ('optimizer.weight_decay', 'training.batch_size', 'training.epochs', 'model.dropout', 'model.hidden_size',
                      'optimizer', 'AdamW(...)'):
            self.assertIn(rows.get(label), (None, 'DISCLOSED'), label)
        self.assertIn('8 disclosed', out)
        for noise in ('log_every', 'output_dir', 'num_workers', 'device', 'shuffle', 'splits', 'test_x'):
            self.assertNotIn(noise, out)
        self.assertNotIn('0.5', out)

        st = json.loads((self.root / '.agentex' / 'status' / 'settings.json').read_text())
        self.assertEqual(set(st), {'tool', 'status', 'summary', 'counts', 'items', 'updated'})
        self.assertEqual((st['tool'], st['status']), ('settings', 'fail'))
        self.assertEqual(st['counts']['mismatch'], 1)
        self.assertLessEqual(len(st['summary']), 100)
        self.assertEqual(st['items'][0]['where'], 'code/config.json:5')
        self.assertTrue(st['updated'].endswith('Z'))
        self.assertEqual((self.root / '.agentex' / '.gitignore').read_text(), '*\n')

    def test_toml_and_fix(self):
        (self.root / 'paper/sections/setup.tex').write_text(
            SETUP_TEX.replace('layers is 6', 'layers is 4') + 'Warmup covers 6\\% of training.\n')
        code, out = run([str(self.root / 'code'), str(self.root / 'paper/main.tex'), '--root', str(self.root)])
        self.assertNotIn('MISMATCH', out)
        if tomllib:
            self.assertNotIn('also 0.06', out)  # the TOML warmup_ratio is now disclosed too
        else:
            self.assertIn('TOML configs skipped', out)
        self.assertEqual(json.loads((self.root / '.agentex/status/settings.json').read_text())['status'], 'warn')



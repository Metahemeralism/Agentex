"""Run: python3 -m unittest discover -s skills/latex-review/scripts"""
import io
import shutil
import subprocess
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

import issues
import rebuttal

MAIN = r"""\documentclass{article}
\input{results}
\begin{document}
\begin{abstract}We do X.\end{abstract}
\section{Introduction}
\input{sec/intro}
\section{Experiments}\label{sec:exp}
\input{sec/exp}
\end{document}
"""
EXP_V1 = "\\subsection{Baselines}\nWe compare with A.\n\\subsection{Ablations}\nNone yet.\n"
EXP_V2 = ("\\subsection{Baselines}\nWe compare with A.\nWe also compare with Longformer (\\res{base.longformer.acc}).\n"
          "\\subsection{Ablations}\nNone yet.\n")
REG = "% Generated by AgenTeX results.py -- do not edit\n\\makeatletter\n{}\\makeatother\n"


def registry(**values):
    return REG.replace('{}', ''.join(f'\\@namedef{{agx@res@{k}}}{{{v}}}\n' for k, v in values.items()))


@unittest.skipUnless(shutil.which('git'), 'needs git')
class RebuttalTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name)
        self.paper = self.repo / 'paper'
        (self.paper / 'sec').mkdir(parents=True)
        self.write('main.tex', MAIN)
        self.write('sec/intro.tex', 'Intro text.\n')
        self.write('sec/exp.tex', EXP_V1)
        self.write('results.tex', registry(**{'main.acc': '0.873'}))
        self.git('init', '-q')
        self.commit('submitted')
        self.git('tag', 'v1')
        # the revision: a new baseline in Experiments > Baselines, a rerun, an unrelated intro edit
        self.write('sec/exp.tex', EXP_V2)
        self.write('results.tex', registry(**{'base.longformer.acc': '0.851', 'main.acc': '0.879'}))
        self.write('sec/intro.tex', 'Intro text, now clearer.\n')
        self.sha = self.commit('Add Longformer baseline')

        led = issues.load(self.paper)
        self.weak, _ = issues.add(led, 'reviewer:R2', '', 'major', 'The baselines are weak: no Longformer.')
        self.intro, _ = issues.add(led, 'reviewer:R2', '', 'minor', 'The introduction overclaims novelty.')
        self.seeds, _ = issues.add(led, 'reviewer:R3', '', 'major', 'Only one seed is reported.')
        issues.set_verdict(led, self.weak, 'fixable', 'add the row', anchor='sec/exp.tex:2')
        issues.fix(led, self.weak, self.sha)
        issues.set_verdict(led, self.intro, 'author', anchor='sec/intro.tex:1')
        issues.save(self.paper, led)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, text):
        (self.paper / rel).write_text(text)

    def git(self, *args):
        cfg = ['-c', 'user.name=t', '-c', 'user.email=t@example.com', '-c', 'commit.gpgsign=false',
               '-c', 'tag.gpgsign=false', '-c', 'core.hooksPath=/dev/null']
        return subprocess.run(['git', *cfg, *args], cwd=self.repo, capture_output=True, text=True, check=True).stdout

    def commit(self, msg):
        self.git('add', '-A')
        self.git('commit', '-q', '-m', msg)
        return self.git('rev-parse', '--short', 'HEAD').strip()

    def blocks(self, md):
        return {i: md.split(f'### {i}')[1].split('###')[0] for i in (self.weak, self.intro, self.seeds)}

    def test_sections_follow_the_input_tree(self):
        index = rebuttal.section_index(self.paper / 'main.tex')
        exp = (self.paper / 'sec' / 'exp.tex').resolve()
        self.assertEqual(rebuttal.section_at(index, exp, 2), 'Experiments › Baselines')
        self.assertEqual(rebuttal.section_at(index, exp, 5), 'Experiments › Ablations')
        self.assertEqual(rebuttal.section_at(index, (self.paper / 'main.tex').resolve(), 4), 'front matter')

    def test_draft_links_changes_to_points(self):
        md, digest = rebuttal.draft(self.paper, 'v1', limit=5000)
        b = self.blocks(md)
        self.assertIn('> The baselines are weak: no Longformer.', b[self.weak])
        self.assertIn('Response: <!--', b[self.weak])
        self.assertIn('- Experiments › Baselines: sec/exp.tex:3-3', b[self.weak])
        self.assertIn(f'- commit {self.sha} Add Longformer baseline', b[self.weak])
        self.assertIn('`\\res{base.longformer.acc}` = 0.851 (new)', b[self.weak])
        self.assertNotIn('intro', b[self.weak])           # the intro edit is a different section
        self.assertIn('- Introduction: sec/intro.tex:1-1', b[self.intro])
        self.assertIn('- none since v1', b[self.seeds])   # no anchor, no fix: nothing invented
        self.assertNotIn('results.tex:', md)              # registry edits are listed as results, not hunks
        self.assertIn('`main.acc` 0.873 → 0.879', md)
        self.assertIn('latexdiff-vc --git --flatten -r v1 main.tex', md)
        self.assertIn('## Reviewer R2 (2 points;', md)
        self.assertIn('## Reviewer R3 (1 point;', md)
        self.assertTrue(digest[0].startswith('R2: 2 points, 2 with linked changes'), digest)

    def test_cli_count_and_no_overwrite(self):
        out = self.paper / 'rebuttal.md'
        run = lambda *a: self._cli('--project', self.paper, *a)
        code, text = run('draft', '--since', 'v1', '--out', out, '--limit-chars', '300')
        self.assertEqual(code, 0, text)
        self.assertEqual(run('draft', '--since', 'v1', '--out', out)[0], 2)  # never clobbers written responses
        filled = out.read_text().replace('Response: <!-- AUTHOR: your argument here -->',
                                         'Response: ' + 'We added the requested baseline. ' * 6, 1)
        out.write_text(filled)
        code, text = run('count', out, '--limit-chars', '300')
        self.assertEqual(code, 1)
        self.assertIn('R2: ', text)
        self.assertIn('OVER by', text.splitlines()[0])
        self.assertNotIn('OVER', text.splitlines()[1])
        self.assertEqual(run('draft', '--since', 'nope', '--out', self.paper / 'x.md')[0], 2)

    def test_posted_chars_skips_internal_lines(self):
        block = '### R2-1 [major]\n\n> abc\n\nResponse: <!-- x -->ok\n\nChanges:\n- Experiments: a.tex:1-2\n- commit 1\n'
        self.assertEqual(rebuttal.posted_chars(block), len('> abc\n\nResponse: ok'))

    @staticmethod
    def _cli(*argv):
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = rebuttal.main([str(a) for a in argv])
        return code, buf.getvalue()


if __name__ == '__main__':
    unittest.main()
